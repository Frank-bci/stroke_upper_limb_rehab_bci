from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]


@dataclass(frozen=True)
class ExperimentRow:
    name: str
    dataset: str
    task: str
    config: str
    split: str
    ba: float | None
    auc: float | None
    f1: float | None
    repeated_ba: str | None
    repeated_auc: str | None
    repeated_f1: str | None
    trigger_rate: float | None
    false_trigger_rate: float | None
    recommendation: str


def main() -> None:
    parser = argparse.ArgumentParser(description="Build a compact experiment result index.")
    parser.add_argument("--outputs-dir", default="outputs")
    parser.add_argument("--json-out", default="outputs/experiment_index.json")
    parser.add_argument("--md-out", default="docs/results-summary.md")
    args = parser.parse_args()

    rows = collect_rows(ROOT / args.outputs_dir)
    index = {
        "summary": {
            "recommended_figshare_trigger_config": "configs/v2/figshare_stroke_full_riemannian_train_channel_standardized.yaml",
            "recommended_physionet_sanity_check_config": "configs/v2/physionet_20_left_right_mi_train_channel_standardized.yaml",
            "notes": [
                "Figshare stroke remains the rehabilitation trigger validation line.",
                "PhysioNet rest-vs-MI is not used as trigger evidence; left-vs-right MI is a healthy-data sanity check.",
                "Tracked artifacts should prefer metrics JSON and docs over model.joblib binaries.",
            ],
        },
        "experiments": [row.__dict__ for row in rows],
    }

    json_path = ROOT / args.json_out
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(index, indent=2, ensure_ascii=False), encoding="utf-8")

    md_path = ROOT / args.md_out
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(render_markdown(rows), encoding="utf-8")


def collect_rows(outputs_dir: Path) -> list[ExperimentRow]:
    rows: list[ExperimentRow] = []
    for metrics_path in sorted(outputs_dir.glob("*/offline_metrics.json")):
        metrics = _read_json(metrics_path)
        experiment_dir = metrics_path.parent
        repeated = _load_repeated_summary(experiment_dir)
        threshold = _load_subject_thresholds(experiment_dir)
        rows.append(
            ExperimentRow(
                name=experiment_dir.name,
                dataset=str(metrics.get("dataset", _infer_dataset(experiment_dir.name))),
                task=_infer_task(metrics, experiment_dir.name),
                config=str(metrics.get("config_path", "")),
                split=str(metrics.get("split_strategy", "")),
                ba=_float(metrics.get("balanced_accuracy")),
                auc=_float(metrics.get("auc")),
                f1=_float(metrics.get("f1")),
                repeated_ba=_format_repeated(repeated, "offline_balanced_accuracy"),
                repeated_auc=_format_repeated(repeated, "offline_auc"),
                repeated_f1=_format_repeated(repeated, "offline_f1"),
                trigger_rate=_float(threshold.get("trigger_rate")) if threshold else None,
                false_trigger_rate=_float(threshold.get("false_trigger_rate")) if threshold else None,
                recommendation=_recommendation(experiment_dir.name),
            )
        )
    return rows


def render_markdown(rows: list[ExperimentRow]) -> str:
    lines = [
        "# Experiment Results Summary",
        "",
        "This file is generated by `scripts/build_results_summary.py` from JSON artifacts under `outputs/`.",
        "",
        "## Current Recommendations",
        "",
        "- Figshare stroke trigger line: `configs/v2/figshare_stroke_full_riemannian_train_channel_standardized.yaml`.",
        "- PhysioNet healthy-data sanity check: `configs/v2/physionet_20_left_right_mi_train_channel_standardized.yaml`.",
        "- Keep metrics/config/docs in Git; keep `model.joblib` local or move binaries to Git LFS.",
        "",
        "## Result Index",
        "",
        "| Experiment | Dataset | Task | Split | BA | AUC | F1 | Repeated BA | Repeated AUC | Trigger | False Trigger | Note |",
        "| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{row.name}`",
                    row.dataset,
                    row.task,
                    row.split,
                    _fmt(row.ba),
                    _fmt(row.auc),
                    _fmt(row.f1),
                    row.repeated_ba or "",
                    row.repeated_auc or "",
                    _fmt(row.trigger_rate),
                    _fmt(row.false_trigger_rate),
                    row.recommendation,
                ]
            )
            + " |"
        )
    lines.extend(
        [
            "",
            "## Reading Guide",
            "",
            "- BA is balanced accuracy from the held-out split in `offline_metrics.json`.",
            "- Repeated metrics are mean ± std from repeated subject split artifacts when available.",
            "- Trigger metrics are personalized subject-threshold aggregates when available.",
            "- PhysioNet left-vs-right MI rows are sanity checks, not rehabilitation trigger evidence.",
            "",
        ]
    )
    return "\n".join(lines)


def _load_repeated_summary(experiment_dir: Path) -> dict[str, Any]:
    for filename in ("repeated_subject_splits.json", "repeated_offline_splits.json"):
        path = experiment_dir / filename
        if path.exists():
            return dict(_read_json(path).get("summary", {}))
    return {}


def _load_subject_thresholds(experiment_dir: Path) -> dict[str, Any]:
    path = experiment_dir / "subject_thresholds.json"
    if not path.exists():
        return {}
    data = _read_json(path)
    aggregate = (
        data.get("aggregate_personalized_metrics")
        or data.get("aggregate")
        or data.get("all_subjects")
        or data.get("selected_metrics")
        or {}
    )
    if isinstance(aggregate, dict):
        return aggregate
    return {}


def _format_repeated(summary: dict[str, Any], key: str) -> str | None:
    value = summary.get(key)
    if not isinstance(value, dict):
        return None
    mean = _float(value.get("mean"))
    std = _float(value.get("std"))
    if mean is None or std is None:
        return None
    return f"{mean:.4f} ± {std:.4f}"


def _recommendation(name: str) -> str:
    if name == "v2_figshare_stroke_full_riemannian_train_channel_standardized":
        return "recommended Figshare v2 trigger baseline"
    if name == "v2_figshare_stroke_full_riemannian_train_channel_standardized_top24":
        return "v2.1 candidate; higher trigger, audit artifact risk"
    if name == "v2_figshare_stroke_full_riemannian_train_channel_standardized_eeg_only":
        return "negative control; lower than full-channel baseline"
    if name == "v2_physionet_20_left_right_mi_train_channel_standardized":
        return "recommended PhysioNet sanity-check baseline"
    if "physionet_20_train_channel_standardized" in name:
        return "rest-vs-MI transfer diagnostic only"
    if "fbcsp" in name and "physionet_20_left_right" in name:
        return "weaker PhysioNet comparator"
    return ""


def _infer_dataset(name: str) -> str:
    if "figshare" in name:
        return "figshare_stroke"
    if "physionet" in name:
        return "physionet"
    if "synthetic" in name:
        return "synthetic"
    return ""


def _infer_task(metrics: dict[str, Any], name: str) -> str:
    config_path = str(metrics.get("config_path", ""))
    if "left_right_mi" in name or "left_right_mi" in config_path:
        return "left_vs_right_mi"
    if "physionet" in name:
        return "rest_vs_mi"
    if "figshare" in name:
        return "rest_vs_motor_intention"
    return ""


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _float(value: Any) -> float | None:
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _fmt(value: float | None) -> str:
    if value is None:
        return ""
    return f"{value:.4f}"


if __name__ == "__main__":
    main()
